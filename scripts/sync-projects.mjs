import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const USER = process.env.GITHUB_USER || "miralexand";
const OUT_FILE = fileURLToPath(
  new URL("../src/generated/projects.generated.ts", import.meta.url),
);

async function fetchRepos() {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": `${USER}-portfolio-sync`,
    "X-GitHub-Api-Version": "2022-11-28",
  };
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  const repos = [];
  for (let page = 1; page <= 5; page += 1) {
    const url = `https://api.github.com/users/${USER}/repos?per_page=100&sort=updated&page=${page}`;
    const res = await fetch(url, { headers });
    if (!res.ok) {
      throw new Error(`GitHub API ${res.status} ${res.statusText}`);
    }
    const batch = await res.json();
    repos.push(...batch);
    if (batch.length < 100) break;
  }
  return repos;
}

function toProject(repo) {
  return {
    name: repo.name,
    description: repo.description || "",
    htmlUrl: repo.html_url,
    homepage: repo.homepage || "",
    language: repo.language || "",
    topics: Array.isArray(repo.topics) ? repo.topics.slice(0, 6) : [],
    stars: repo.stargazers_count || 0,
    forks: repo.forks_count || 0,
    updatedAt: repo.pushed_at || repo.updated_at || "",
    createdAt: repo.created_at || "",
  };
}

function render(projects, syncedAt) {
  return `// Auto-generated by scripts/sync-projects.mjs. Do not edit by hand.

export type ProjectRepo = {
  name: string;
  description: string;
  htmlUrl: string;
  homepage: string;
  language: string;
  topics: string[];
  stars: number;
  forks: number;
  updatedAt: string;
  createdAt: string;
};

export const projectsSyncedAt = ${JSON.stringify(syncedAt)};

export const githubProjects: ProjectRepo[] = ${JSON.stringify(projects, null, 2)};
`;
}

async function main() {
  let repos;
  try {
    repos = await fetchRepos();
  } catch (error) {
    console.warn(`[sync-projects] ${error.message}`);
    try {
      await readFile(OUT_FILE, "utf8");
      console.warn("[sync-projects] Keeping the existing snapshot.");
      return;
    } catch {
      console.warn("[sync-projects] No snapshot found; writing an empty one.");
      repos = [];
    }
  }

  const projects = repos
    .filter((repo) => !repo.fork && !repo.archived)
    .map(toProject)
    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));

  const syncedAt = new Date().toISOString();
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, render(projects, syncedAt), "utf8");
  console.log(
    `[sync-projects] Synced ${projects.length} repositories at ${syncedAt}.`,
  );
}

await main();
